#pragma once

#include "collide.h"
#include "types.h"

#include <optional>

namespace xge
{
	// The four ways a thing can be sent, face or hop.
	enum class Direction { Up, Down, Left, Right };

	// The arithmetic of the movement verbs, in one place of its own with nothing
	// in it but the standard library: where a thing is put when it sticks to a
	// wall or comes in again at the other side, where a hop or a jump takes it,
	// where a shot leaves a shooter and which way, which way an aim or a chase
	// goes, how high a leap rises, where a thing stands, climbs and flies. It is
	// the one copy of this code there is. The engine (CommandExecutor and Game)
	// calls it with an Object's numbers, and a game generated by xgecli
	// --generate gets these files copied in beside its own main.cpp and calls it
	// with the numbers of an SFML shape, so a generated game moves as the engine
	// does. What it never does is decide when: the rules and the frame are the
	// engine's and the program's own.
	namespace motion
	{
		// The way of the four that is nearest to `way`: the axis it goes further
		// along (a tie goes along x).
		Direction directionOf(const Vector2f& way) noexcept;

		// `distance` pixels the given way: (0, -distance) for up, and so on.
		Vector2f along(Direction direction, float distance) noexcept;

		// The way a heading points (degrees clockwise from straight up, 0 up and
		// 90 right), one pixel long.
		Vector2f ahead(float degrees) noexcept;

		// The heading, from 0 up to (not including) 360, that points along `way`.
		float headingOf(const Vector2f& way) noexcept;

		// Whether a thing of `size` at `position` is wholly inside a window `width`
		// by `height`: what a hop or a jump must end in to be made.
		bool fits(const Vector2f& position, const Vector2f& size, float width, float height) noexcept;

		// A thing stuck to an edge it has touched: put back inside the window on
		// that edge's own axis, and losing only the velocity that was carrying it
		// into the wall, so a thing pressed against the floor still slides. The
		// other axis is left alone.
		void stick(Vector2f& position, Vector2f& velocity, const Vector2f& size, float width, float height, Edge edge) noexcept;

		// A thing that has gone right off the window through `edge`, and is still
		// heading that way (`heading` is its velocity and what it rides), comes in
		// again from the opposite side, one window and one of its own sizes
		// along, so things spaced along a lane stay spaced. Until it has gone
		// completely nothing happens. Whether it did.
		bool wrap(Vector2f& position, const Vector2f& size, const Vector2f& heading, float width, float height, Edge edge) noexcept;

		// The way out through an edge, one pixel long: what a thing that is only
		// ever moved by keys, with no velocity to ask, can be taken to head.
		Vector2f outward(Edge edge) noexcept;

		// The step of a jump that takes `frames` frames to go `distance` the given
		// way, if it would land inside the window; none if it would not (it is
		// not made at all, not part of the way).
		std::optional<Vector2f> jumpStep(const Vector2f& position, const Vector2f& size, Direction direction, float distance, int frames, float width, float height) noexcept;

		// Coming down onto the top of another thing (its own bottom edge touched,
		// not going up, not on a ladder): it stands there. Put on the top, its fall
		// stopped. Whether it landed; any other touch does nothing, so a platform
		// can be walked past and jumped up through.
		bool land(Vector2f& position, Vector2f& velocity, const Vector2f& size, float topOfOther, Edge edgeOfMover, bool climbing) noexcept;

		// The speed up, a negative number, at which a thing leaves the ground to
		// rise `height` pixels against a pull of `pull` a frame: v * v = 2 * pull *
		// height.
		float leapSpeed(float pull, float height) noexcept;

		// Whether a climber is at a ladder: its middle over it, and its feet
		// between the ladder's top and bottom (half a pixel either way).
		bool atLadder(const Vector2f& climberPosition, const Vector2f& climberSize, const Vector2f& ladderPosition, const Vector2f& ladderSize) noexcept;

		// What a frame at a ladder did: whether the climber moved (it did nothing
		// when it could not get on), and whether it got off at an end of the
		// ladder, standing there, which leaves the way across to the keys held then.
		struct Climbed
		{
			bool moved{ false };
			bool gotOff{ false };
		};

		// One frame of a climb at a ladder, `step` the way the keys held climb (up
		// is below 0). Off it, it gets on only from the ground and when it can go
		// that way, lined up with the ladder's middle. On it, it goes the step, its
		// feet kept between the ladder's ends, with no velocity so that nothing
		// walks it off.
		Climbed climb(Vector2f& position, Vector2f& velocity, const Vector2f& size, bool& climbing, bool grounded, float step, const Vector2f& ladderPosition, const Vector2f& ladderSize) noexcept;

		// Where a shot is put, and the velocity it leaves with.
		struct Launch
		{
			Vector2f position;
			Vector2f velocity;
		};

		// From the middle of the side the shooter faces, just clear of it, moving
		// that way at `speed`.
		Launch shotFacing(const Vector2f& shooter, const Vector2f& shooterSize, const Vector2f& shotSize, Direction facing, float speed) noexcept;

		// From the middle of the shooter, just clear of it along `aim` (one pixel
		// long), at `speed`.
		Launch shotAlong(const Vector2f& shooter, const Vector2f& shooterSize, const Vector2f& shotSize, const Vector2f& aim, float speed) noexcept;

		// From the nose of a shooter with a heading: out by half its longer side
		// along the heading, at `speed`.
		Launch shotAhead(const Vector2f& shooter, const Vector2f& shooterSize, const Vector2f& shotSize, float heading, float speed) noexcept;

		// From the top centre of a shooter with none of those: the shot's own
		// middle over the shooter's, at the velocity the shot has of its own.
		Launch shotUp(const Vector2f& shooter, const Vector2f& shooterSize, const Vector2f& shotSize, const Vector2f& shotVelocity) noexcept;

		// The way from the middle of one thing to the middle of another, one pixel
		// long (<aim>); none when they are the same place.
		std::optional<Vector2f> aimed(const Vector2f& from, const Vector2f& to) noexcept;

		// Heading straight for the middle of another thing at `speed`
		// (<chase>): its velocity, and the way it set off, one pixel long. Within
		// `stopWithin` of it, or on it, it stops instead and there is no way.
		struct Chase
		{
			Vector2f velocity;
			std::optional<Vector2f> way;
		};

		Chase chased(const Vector2f& from, const Vector2f& to, float speed, float stopWithin) noexcept;

		// A thing's velocity after a frame of pull and thrust (`change`, added
		// first) and drag (the fraction of what is left that it loses).
		Vector2f accelerated(const Vector2f& velocity, const Vector2f& change, float drag) noexcept;

		// One frame of a leg of a path, flown at `speed` pixels a frame. `left` is
		// what is left of a step, or, for a leg that goes home, the way from where
		// it is to there. The velocity that takes it on and what is then left,
		// or, when there is next to nothing left, that the leg is done.
		struct Flight
		{
			bool done{ false };
			Vector2f velocity;
		};

		Flight fly(const Vector2f& left, float speed) noexcept;
	}
}
