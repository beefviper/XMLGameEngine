#pragma once

#include "bitmap.h"
#include "types.h"

#include <optional>

namespace xge
{
	// Which side of a screen or of another thing's bounding box was touched.
	enum class Edge { Top, Bottom, Left, Right };

	// The edge you'd see the same contact from, standing on the other thing:
	// if you hit something's Left edge, you were hit on your own Right.
	Edge opposite(Edge edge) noexcept;

	// The geometry of touching, in one place of its own with nothing in it but
	// the standard library: where two things are, which side they touch on, when
	// in a step they first meet, and where a thing goes after it hits one. It is
	// the one copy of this code there is. The engine (CollisionDetector and
	// CommandExecutor) uses it from lib/, and a game generated by xgecli
	// --generate gets these files copied in beside its own main.cpp, so a
	// generated game decides a touch as the engine does.
	namespace collide
	{
		// A thing as the geometry sees it: a box, or a circle that fits in its
		// size, at a position, and, when it is touched by its pixels, its picture.
		struct Body
		{
			Vector2f position;
			Vector2f size;

			// A circle (as wide as size.x) instead of a box.
			bool circle{ false };

			// Touched by its drawn pixels, which are `picture` (a `Bitmap` whose
			// clear pixels are not part of it). A thing of this kind with no
			// picture, or any thing in a pair with one that has, is solid all over
			// its shape.
			bool pixels{ false };
			const Bitmap* picture{ nullptr };
		};

		// When, within one step of motion, two things first touch.
		struct SweepHit
		{
			// How far through the step it happens: 0 is the start (they were
			// already touching), 1 is the end of the move.
			float time{};

			// The edge of the second thing that was hit.
			Edge edgeOfSecond{ Edge::Top };
		};

		// Has `body` crossed the given edge of a screen `width` by `height`?
		bool touchesScreenEdge(const Body& body, float width, float height, Edge edge);

		// A plain axis-aligned bounding-box overlap test - exact enough on its
		// own for two rectangles. Returns which edge of `b` was hit by `a`.
		std::optional<Edge> rectangleRectangle(const Body& a, const Body& b);

		// A closer geometric test for when at least one participant is a
		// circle, where a bounding-box overlap alone isn't precise enough
		// (e.g. the ball brushing past a corner). Returns which edge of `rect`
		// was hit by `circle`, however far into it the circle's centre is.
		std::optional<Edge> circleRectangle(const Body& circle, const Body& rect);

		// Are the two overlapping right now? Picks the right test above for the
		// shapes involved, and returns which edge of `b` was hit by `a`. When
		// either is touched by its pixels this is also the second test: the boxes
		// have to overlap first, and then some pixel of each has to lie on a pixel
		// of the other. The edge is then still the boxes' edge.
		std::optional<Edge> overlap(const Body& a, const Body& b);

		// Whether either of the two is touched by its pixels.
		bool usesPixels(const Body& a, const Body& b) noexcept;

		// Do any two pixels, one drawn by each, fall on the same spot on the
		// screen? Each pixel of the screen is asked about at its centre.
		bool pixelsOverlap(const Body& a, const Body& b);

		// Moves `a` by moveA and `b` by moveB over one step and finds the first
		// moment they touch, if they do at all. Unlike checking where the two
		// end up, this cannot miss a small or fast thing passing straight through
		// a thin one between two frames. Two things that already overlap are a
		// hit at time 0; two that merely touch and are moving apart are not a hit.
		// A pair touched by pixels is swept as boxes first and then walked along
		// the same path, half a pixel at a time, from the moment the boxes touch
		// until pixels do, and the edge reported is the one the motion came in
		// through.
		std::optional<SweepHit> sweep(const Body& a, const Vector2f& moveA, const Body& b, const Vector2f& moveB);

		// The velocity of something that hit the given edge of another thing and
		// is to bounce off it: the part that went into the edge turned round.
		Vector2f bounced(const Vector2f& velocity, Edge edge) noexcept;

		// The velocity after a bounce off `other` that leaves at an angle set by
		// where it hit, with `mover` where it touched (not where the step ended).
		// `edge` is the edge of the mover that touched (as a rule says it, the
		// opposite of what sweep reports for the other thing). How far the
		// mover's middle is from the middle of the side it touched, as a share of
		// half that side's length (-1 at one end, 1 at the other, held there past
		// the ends), times maxAngle, is the angle away from straight back out,
		// towards the end it hit nearer to. The speed is what it was.
		Vector2f deflected(const Vector2f& velocity, const Body& mover, const Body& other, Edge edge, float maxAngle);
	}
}
